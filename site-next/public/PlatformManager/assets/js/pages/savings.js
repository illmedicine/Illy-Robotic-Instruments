import { h, icon, fmt, pill } from "../dom.js";
import { api } from "../api.js";
import { dataTable } from "../ui.js";
import { barList } from "../charts.js";
import { pageHead, noData } from "./common.js";

const SEV = { high: "risk", medium: "warn", low: "info" };
const money = (n, cur = "USD") => new Intl.NumberFormat(undefined, { style: "currency", currency: cur, maximumFractionDigits: 0 }).format(n || 0);

export async function render(ctx) {
  const [a, ai] = await Promise.all([api.analytics(), api.aiStatus()]);
  const root = h("div", {}, pageHead("Savings & insights", "Where spend and risk can come down, ranked by estimated monthly savings."));
  if (!a) return root.append(noData(ctx, "platform", "Analytics")), root;

  const aiOut = h("div");
  const aiBtn = h("button", { class: "btn", type: "button", disabled: !ai.enabled, title: ai.enabled ? "" : "Turn on the ai section in config/powerplatform.json" }, h("span", { class: "spark" }), "AI summary");
  aiBtn.onclick = async () => {
    aiBtn.disabled = true;
    aiOut.replaceChildren(h("div", { class: "loading", text: "Analysing..." }));
    try {
      const r = await api.aiInsights();
      aiOut.replaceChildren(
        h("p", { text: r.summary }),
        r.actions.map((x) => h("div", { class: "aiaction" }, h("b", { text: x.title }), " ", pill(x.effort + " effort", ""),
          x.estimatedMonthlySavings != null ? pill("~" + money(x.estimatedMonthlySavings, a.currency) + "/mo", "ok") : null, h("div", { class: "muted", text: x.why }))),
        h("div", { class: "muted", text: `Generated by ${r.provider}${r.provider === "demo" ? " (canned demo output)" : ""}. Review before acting.` }));
    } catch (e) { aiOut.replaceChildren(h("div", { class: "banner error", text: e.message })); }
    aiBtn.disabled = false;
  };

  root.append(h("div", { class: "card hero" }, h("div", { class: "row" },
    h("div", {}, h("div", { class: "cap", text: "Estimated savings per month" }), h("div", { class: "big", text: money(a.savingsMonthly, a.currency) })),
    h("div", {}, h("div", { class: "cap", text: "Per year" }), h("div", { class: "big", text: money(a.savingsAnnual, a.currency) })),
    h("div", {}, h("div", { class: "cap", text: `${a.recommendations.length} recommendations` }), h("div", { class: "cap", text: a.pricingNote })))));

  root.append(h("div", { class: "section" }, h("div", { class: "card aibox" }, h("h3", {}, icon("chart"), "AI analysis",
    h("span", { class: "sub", text: ai.enabled ? `provider: ${ai.provider}${ai.includePersonalData ? "" : " (aggregates only, no names sent)"}` : "off" }), aiBtn), aiOut)));

  root.append(h("div", { class: "section" }, h("h2", { text: "Recommendations" }),
    a.recommendations.length ? a.recommendations.map((r) => h("div", { class: "card rec " + r.severity, style: { marginBottom: "12px" } },
      h("h3", {}, pill(r.severity, SEV[r.severity]), r.title, pill(r.confidence + " confidence", ""),
        r.savingsMonthly ? h("span", { class: "money", text: money(r.savingsMonthly, a.currency) + "/mo" }) : h("span", { class: "sub", text: `${fmt.n(r.count)} item(s)` })),
      h("div", { class: "muted", text: r.detail }),
      h("details", {}, h("summary", { text: `Show ${fmt.n(r.count)} item(s)` }), dataTable({ rows: r.items, csvName: r.id, pageSize: 10, columns: [
        { key: "name", label: "Item" }, { key: "env", label: "Where" }, { key: "info", label: "Detail" }] }))))
      : h("div", { class: "card empty", text: "No savings opportunities found in the data collected so far." })));

  root.append(h("div", { class: "section grid g-2" },
    h("div", { class: "card" }, h("h3", { text: "Flows and apps by department" }),
      barList(a.byDepartment.slice(0, 10).map((d) => ({ label: d.department, value: d.flows + d.apps })))),
    h("div", { class: "card" }, h("h3", { text: "Premium-connector flows by department" }),
      barList(a.byDepartment.filter((d) => d.premiumFlows).slice(0, 10).map((d) => ({ label: d.department, value: d.premiumFlows })), { warm: true }))));

  root.append(h("div", { class: "section" }, h("h2", { text: "By department" }), dataTable({ rows: a.byDepartment, csvName: "departments", columns: [
    { key: "department", label: "Department" }, { key: "licensedUsers", label: "Licensed users", num: true }, { key: "inactiveLicences", label: "Inactive", num: true },
    { key: "flows", label: "Flows", num: true }, { key: "apps", label: "Apps", num: true }, { key: "premiumFlows", label: "Premium flows", num: true }, { key: "suspended", label: "Suspended", num: true }] })));
  root.append(h("div", { class: "section" }, h("h2", { text: "By owner" }), dataTable({ rows: a.byOwner, csvName: "owners", searchText: (r) => r.owner + " " + r.department, columns: [
    { key: "owner", label: "Owner" }, { key: "department", label: "Department" }, { key: "flows", label: "Flows", num: true }, { key: "apps", label: "Apps", num: true },
    { key: "state", label: "Account", render: (r) => pill(r.state, r.state === "active" ? "ok" : r.state === "unknown" ? "" : "risk") }] })));
  root.append(h("div", { class: "section" }, h("h2", { text: "By connector" }), dataTable({ rows: a.byConnector, csvName: "connectors", searchText: (r) => r.connector, columns: [
    { key: "connector", label: "Connector", render: (r) => fmt.connector(r.connector) }, { key: "premium", label: "Tier", render: (r) => pill(r.premium ? "Premium" : "Standard", r.premium ? "warn" : ""), csv: (r) => (r.premium ? "Premium" : "Standard") },
    { key: "flows", label: "Flows", num: true }, { key: "apps", label: "Apps", num: true }] })));
  return root;
}
